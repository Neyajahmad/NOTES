package Pattern_Printing;

import java.util.Scanner;

// diamond pattern mean a full pyramid
public class Diamond_Pattern{
    public static void main(String args[]){
        Scanner sc=new Scanner(System.in);
        int n=sc.nextInt();
        for(int i=1;i<=n;i++){
            for(int j=1;j<=n-i;j++){
                System.out.print(" ");
            }
            for(int j=1;j<=2*i-1;j++){
                System.out.print("*");
            }
            System.out.println();
        }


        for(int i=1;i<=n;i++){
            for(int j=1;j<i;j++){
                System.out.print(" ");
            }
            for(int j=1;j<=(2*(5-i)+1);j++){
                System.out.print("*");
            }
            System.out.println();
        }
    }
}